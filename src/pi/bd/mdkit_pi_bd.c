static void bd_trigger(void *state) { ((mdkit_pi_bd *)state)->events.trigger = 1; }
static void bd_block(mdkit_pi_bd *s) {
  mdkit_pi_bd_modal *c = &s->body;
  uint32_t *w = c->work, *y = c->fraction;
  uint32_t old = s->attack;
  s->attack = mdkit_acc_to_word(mdkit_mpy(old, 0x7c28f6));
  uint64_t a = mdkit_add(mdkit_mpy(s->tension, old), mdkit_from24(0x400000));
  a = mdkit_asl(mdkit_mpy(mdkit_acc_to_word(a), s->pitch), 1);
  y[0xfe] = mdkit_acc_to_word(a);
  mdkit_pi_bd_modal_excitation(c, &s->phase_hi, &s->phase_lo, mdkit_asr(a, 22), 0x142859);
  uint32_t idx = mdkit_acc_to_word(mdkit_mpy(0x42, s->decay));
  uint32_t coupling = mdkit_pi_bd_modal_x(c, 0x142b49 + idx);
  uint32_t feedback = mdkit_acc_to_word(mdkit_mpy(coupling, 0x5a827a));
  w[0xfb] = coupling;
  w[0xfc] = feedback;

  uint64_t input = mdkit_from24(s->excitation_filter);
  const unsigned stride[3] = {0x10b, 0xff, 0xb5};
  for (unsigned branch = 0; branch < 3; ++branch) {
    unsigned pointer =
        mdkit_pi_bd_modal_wrap(s->delay_pointer[branch], stride[branch], 511);
    uint64_t b = mdkit_from24(s->delay_filter[branch]);
    uint32_t delayed = s->delay[pointer - 0x135600];
    pointer = mdkit_pi_bd_modal_wrap(pointer, 1, 511);
    for (unsigned i = 0; i < 32; ++i) {
      if (!branch) {
        uint32_t source = w[0x40 + i];
        w[0x40 + i] = mdkit_acc_to_word(input);
        w[0x60 + i] = mdkit_acc_to_word(input);
        uint32_t previous = mdkit_acc_to_word(input);
        input = mdkit_mac(input, source, s->hammer);
        input = mdkit_sub(input, mdkit_mpy(previous, s->hammer));
      }
      w[0x80 + 32 * branch + i] = mdkit_acc_to_word(b);
      uint32_t previous = mdkit_acc_to_word(b);
      b = mdkit_mac(b, delayed, s->damp);
      b = mdkit_sub(b, mdkit_mpy(previous, s->damp));
      delayed = s->delay[pointer - 0x135600];
      pointer = mdkit_pi_bd_modal_wrap(pointer, 1, 511);
    }
    s->delay_filter[branch] = mdkit_acc_to_word(b);
  }
  s->excitation_filter = mdkit_acc_to_word(input);

  unsigned p0 = s->delay_pointer[0], p1 = s->delay_pointer[1],
           p2 = s->delay_pointer[2];
  uint32_t x0 = w[0x60];
  uint64_t b = mdkit_mpy(x0, 0x51eb8);
  b = mdkit_mac(b, feedback, w[0xa0]);
  a = mdkit_mpy(w[0x60], 0x51eb8);
  a = mdkit_mac(a, coupling, w[0x80]);
  b = mdkit_mac(b, feedback, w[0xc0]);
  for (unsigned i = 0; i < 32; ++i) {
    uint32_t src = w[0x60 + i], middle = w[0xa0 + i], last = w[0xc0 + i];
    uint32_t va = mdkit_acc_to_word(a), vb = mdkit_acc_to_word(b);
    a = mdkit_mpy(src, 0x51eb8);
    s->delay[p2 - 0x135600] = va;
    p2 = mdkit_pi_bd_modal_wrap(p2, 1, 511);
    a = mdkit_sub(a, mdkit_mpy(feedback, middle));
    s->delay[p1 - 0x135600] = vb;
    p1 = mdkit_pi_bd_modal_wrap(p1, 1, 511);
    a = mdkit_mac(a, feedback, last);
    b = mdkit_mpy(w[0x61 + i], 0x51eb8);
    b = mdkit_mac(b, feedback, w[0xa1 + i]);
    s->delay[p0 - 0x135600] = mdkit_acc_to_word(a);
    p0 = mdkit_pi_bd_modal_wrap(p0, 1, 511);
    a = mdkit_mpy(w[0x61 + i], 0x51eb8);
    a = mdkit_mac(a, coupling, w[0x81 + i]);
    b = mdkit_mac(b, feedback, w[0xc1 + i]);
  }
  s->delay_pointer[0] = p0;
  s->delay_pointer[1] = p1;
  s->delay_pointer[2] = p2;

  b = mdkit_from24(s->feedback_hi);
  uint32_t previous = s->feedback_prev;
  x0 = w[0xa0];
  for (unsigned i = 0; i < 32; ++i) {
    a = mdkit_add(mdkit_sub(mdkit_from24(w[0xc0 + i]), mdkit_from24(x0)),
               mdkit_from24(w[0x80 + i]));
    x0 = mdkit_acc_to_word(b);
    b = mdkit_mpy(0x59999a, x0);
    b = mdkit_sub(b, mdkit_mpy(0x400000, previous));
    previous = mdkit_acc_to_word(a);
    a = mdkit_from24(w[0x40 + i]);
    a = mdkit_add(a, mdkit_from24(x0));
    a = mdkit_asl(a, 2);
    b = mdkit_mac(b, 0x400000, previous);
    x0 = w[0xa1 + i];
    w[0x40 + i] = mdkit_acc_to_word(a);
  }
  s->feedback_hi = mdkit_acc_to_word(b);
  s->feedback_prev = previous;
  mdkit_pi_bd_modal_coefficients(c, y[0xfe], s->decay, 0x142279, 0x142289);
  mdkit_pi_bd_modal_filter(c);
  for (unsigned i = 0; i < 32; ++i)
    s->block[i] = w[0x40 + i];
}
static void bd_render(void *state, float *out, unsigned frames) {
  mdkit_pi_bd *s = state;
  while (frames) {
    if (s->pos == 32) {
      unsigned e = mdkit_events_boundary(&s->clock, &s->events, 0);
      if (e & MDKIT_PI_PUBLISH)
        bd_controls(s);
      if (e & MDKIT_PI_FIRST)
        bd_activate(s);
      if (e & MDKIT_PI_TRIGGER) {
        s->phase_lo = 0;
        s->phase_hi = 0x142291;
        s->attack = 0x7fffac;
      }
      bd_block(s);
      s->pos = 0;
    }
    unsigned n = 32 - s->pos;
    if (n > frames)
      n = frames;
    for (unsigned i = 0; i < n; ++i)
      out[i] = s->events.triggered ? (float)mdkit_s24(s->block[s->pos + i]) / 8388608.0f : 0.0f;
    s->pos += n;
    out += n;
    frames -= n;
  }
}
