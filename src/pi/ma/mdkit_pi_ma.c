static void mdkit_pi_ma_packet(const float k[8],uint32_t out[6]){
out[0]=mdkit_pi_ma_word0((unsigned)(128*k[0]));
out[1]=mdkit_pi_ma_gain[((unsigned)k[0])*128+(unsigned)k[2]];
out[2]=mdkit_pi_ma_word2((unsigned)(128*k[1]));
out[3]=mdkit_pi_ma_word3((unsigned)(128*k[2]));
out[4]=mdkit_pi_ma_word4((unsigned)(128*k[4]));
out[5]=6342141;
}


static uint64_t ma_sub_round(uint64_t a, uint32_t x, uint32_t y) {
  a = mdkit_sub(a, mdkit_mpy(x, y));
  a = mdkit_add(a, UINT64_C(1) << 23);
  if (!(a & MD_MASK24))
    a &= ~(UINT64_C(1) << 24);
  return a & ~UINT64_C(0xffffff);
}
static void ma_packet(mdkit_pi_ma *s) {
  uint32_t p[6];
  mdkit_pi_ma_packet(s->clock.current, p);
  s->grain_threshold = p[0];
  s->output_gain = p[1];
  s->decay = p[2];
  s->grain_memory = p[3];
  s->feedback_a = p[4];
  s->feedback_b = p[5];
}
static void ma_activate(mdkit_pi_ma *s) {
  s->noise_a = 0x2228;
  s->noise_b = 0x442;
  s->envelope = s->grain_level = s->filter_a = s->filter_b = s->previous = 0;
}
static void ma_init(void *state) {
  mdkit_pi_ma *s = state;
  /* Reset caller-owned storage, including clock and filter history. */
  for (unsigned i = 0; i < sizeof *s; ++i) ((unsigned char *)s)[i] = 0;

  mdkit_events_init(&s->clock, &s->events);
  s->pos = 32;
  ma_packet(s);
  ma_activate(s);
  for (unsigned i = 0; i < 32; ++i)
    s->block[i] = 0;
}
static void ma_target(void *state, unsigned i, unsigned v) {
  mdkit_events_target(&((mdkit_pi_ma *)state)->events, 5, i, v);
}
static void ma_trigger(void *state) { ((mdkit_pi_ma *)state)->events.trigger = 1; }
static void ma_block(mdkit_pi_ma *s) {
  uint32_t noise[32];
  uint64_t b = mdkit_from24(s->noise_a);
  uint32_t x1 = s->noise_b;

  for (unsigned i = 0; i < 31; ++i) {
    b = mdkit_add(b, mdkit_from24(x1));
    uint32_t old = x1;
    noise[i] = mdkit_mid(b);
    x1 = mdkit_mid(b);
    b = mdkit_setmid(b, old);
  }
  b = mdkit_add(b, mdkit_from24(x1));
  s->noise_a = x1;
  s->noise_b = mdkit_mid(b);
  noise[31] = mdkit_mid(b);
  for (unsigned i = 0; i < 32; ++i) {
    uint64_t a = mdkit_mpy(s->grain_level, s->grain_memory);
    int64_t magnitude = mdkit_s24(noise[i]);
    if (magnitude < 0)
      magnitude = -magnitude;
    const uint32_t envelope = s->envelope;
    if (magnitude <= mdkit_s24(s->grain_threshold))
      a = mdkit_add(a, mdkit_from24(envelope));
    s->grain_level = mdkit_acc_to_word(a);
    a = mdkit_mpyr(mdkit_acc_to_word(a), noise[i]);
    b = mdkit_mpyr(s->output_gain, mdkit_acc_to_word(a));
    a = mdkit_asr(mdkit_asl(b, 3), 1);
    a = ma_sub_round(a, s->filter_a, s->feedback_a);
    a = mdkit_asl(a, 1);
    a = ma_sub_round(a, s->filter_b, s->feedback_b);
    s->filter_b = s->filter_a;
    s->filter_a = mdkit_acc_to_word(a);
    a = mdkit_sub(mdkit_from24(s->filter_b), mdkit_from24(s->previous));
    s->previous = s->filter_b;
    b = mdkit_mpy(envelope, s->decay);
    s->block[i] = mdkit_acc_to_word(a);
    s->envelope = mdkit_acc_to_word(b);
  }
}
static void ma_render(void *state, float *out, unsigned frames) {
  mdkit_pi_ma *s = state;
  while (frames) {
    if (s->pos == 32) {
      unsigned e = mdkit_events_boundary(&s->clock, &s->events, 0);
      if (e & MDKIT_PI_PUBLISH)
        ma_packet(s);
      if (e & MDKIT_PI_FIRST)
        ma_activate(s);
      if (e & MDKIT_PI_TRIGGER)
        s->envelope = 0x66666;
      ma_block(s);
      s->pos = 0;
    }
    unsigned n = 32 - s->pos;
    if (n > frames)
      n = frames;
    for (unsigned i = 0; i < n; ++i)
      out[i] = s->events.triggered ? (float)mdkit_s24(s->block[s->pos + i]) / 8388608.0f : 0.0f;
    s->pos += n;
    out += n;
    frames -= n;
  }
}
