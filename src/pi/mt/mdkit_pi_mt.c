enum { MDKIT_PI_PUBLISH = 1, MDKIT_PI_TRIGGER = 2, MDKIT_PI_FIRST = 4 };
static inline void mdkit_events_init(mdkit_control_clock *c, mdkit_pi_mt_events *e) {

  for(unsigned i=0;i<8u;++i){const float v=(float)mdkit_pi_mt_defaults[i];c->target[i]=c->raw[i]=c->current[i]=c->pending[i]=v;}
  c->count = 8; c->block = 0; c->publish_block = 0; c->pending_valid = 0;
  c->next_update = 2;
  e->targets = e->trigger = e->triggered = 0;
  for (unsigned i = 0; i < 8; ++i) {
    e->queued[i] = mdkit_pi_mt_defaults[i];
    e->last_raw[i] = (unsigned)mdkit_pi_mt_defaults[i] * 128u;
  }
}
static inline void mdkit_events_target(mdkit_pi_mt_events *e, unsigned count,
                                       unsigned i, unsigned value) {
  if (i < count) {
    e->queued[i] = value > 127 ? 127 : value;
    e->targets |= 1u << i;
  }
}
static inline unsigned
mdkit_events_boundary(mdkit_control_clock *c, mdkit_pi_mt_events *e, int trigger_only) {
  unsigned result = 0;
  if (c->pending_valid && c->block >= c->publish_block) {
    for (unsigned i = 0; i < 8; ++i)
      c->current[i] = c->pending[i];
    c->pending_valid = 0;
    result = MDKIT_PI_PUBLISH;
  }
  if (c->block == c->next_update) {

    for (unsigned i = 0; i < 8; ++i) {
      uint32_t raw = (uint32_t)(128.0f * c->raw[i]);
      c->pending[i] = c->raw[i];
      e->last_raw[i] = raw;
      c->raw[i] =
          (float)((3 * raw + 128 * (uint32_t)c->target[i]) / 4) / 128.0f;
    }
    c->pending_valid = !trigger_only;
    c->publish_block = c->block + 1;
    c->next_update += 12;
  }
  for (unsigned i = 0; i < 8; ++i)
    if (e->targets & (1u << i))
      c->target[i] = (float)e->queued[i];
  e->targets = 0;
  if (e->trigger) {
    for (unsigned i = 0; i < 8; ++i)
      c->current[i] = c->raw[i];
    result = MDKIT_PI_PUBLISH | MDKIT_PI_TRIGGER | (e->triggered ? 0 : MDKIT_PI_FIRST);
    e->trigger = 0;
    e->triggered = 1;
  }
  ++c->block;
  return result;
}

static inline __attribute__((unused)) uint32_t mdkit_pi_mt_modal_x(mdkit_pi_mt_modal *c, uint32_t address) {
  if (address < 512u) return c->work[address];
  if (address >= 0x142000u && address < 0x145000u) return mt_rom(address);
  return mt_boot_x(address);
}
static inline __attribute__((unused)) uint32_t mdkit_pi_mt_modal_y(mdkit_pi_mt_modal *c, uint32_t address) {
  if (address < 512u) return c->fraction[address];
  return (address >= 0x142000u && address < 0x145000u) ? mt_rom(address) : 0u;
}
static inline __attribute__((unused)) void mdkit_pi_mt_modal_reset(mdkit_pi_mt_modal *c) {
  for (unsigned i = 0; i < 512; ++i) {
    c->work[i] = mt_boot_x(i);
    c->fraction[i] = mt_boot_y(i);
  }
  for (unsigned i = 0; i < 8; ++i)
    for (unsigned j = 0; j < 3; ++j)
      c->history[i][j] = 0;
}
static inline __attribute__((unused)) void mdkit_pi_mt_modal_clear_modes(mdkit_pi_mt_modal *c) {
  for (unsigned i = 0; i < 8; ++i)
    for (unsigned j = 0; j < 3; ++j)
      c->history[i][j] = 0;
}
static inline __attribute__((unused)) uint32_t mdkit_pi_mt_modal_wrap(uint32_t p, int step, unsigned m) {
  unsigned mask = 1;
  while (mask <= m)
    mask <<= 1;
  --mask;
  int64_t v = (int64_t)p + step;
  unsigned base = p & ~mask;
  int64_t span = ((unsigned)step & mask) ? m + 1 : 0;
  if (v < base)
    v += span;
  if (v > base + m)
    v -= span;
  return (uint32_t)v & MD_MASK24;
}
/* Integer/fraction phase identifies two adjacent waveform words; complementary
 * unsigned fractions are generated before either table read. */
static inline __attribute__((unused)) void mdkit_pi_mt_modal_excitation(mdkit_pi_mt_modal *c, uint32_t *hi,
                                       uint32_t *lo, uint64_t step,
                                       uint32_t end) {
  c->work[64] = 0x7fffff;
  c->fraction[64] = 0xffffff;
  uint64_t phase = mdkit_from48(mdkit_pack48(*hi, *lo));
  for (unsigned i = 0; i < 32; ++i) {
    phase = mdkit_add(phase, step);
    uint64_t complement = mdkit_sub(mdkit_from48(UINT64_C(0x7fffffffffff)), phase);
    uint64_t v = mdkit_to48(phase);
    c->work[i] = mdkit_mid(v);
    c->fraction[i] = mdkit_low(v);
    c->fraction[32 + i] = mdkit_low(complement);
  }
  if (mdkit_s56(phase) >= mdkit_s56(mdkit_from24(end)))
    phase = mdkit_from24(end);
  *hi = mdkit_mid(phase);
  *lo = mdkit_low(phase);
  uint32_t first = mdkit_pi_mt_modal_x(c, c->work[0]);
  for (unsigned i = 0; i < 32; ++i) {
    uint32_t index = c->work[i];
    uint64_t a = mdkit_mpy_su(first, c->fraction[32 + i]);
    a = mdkit_add(a, mdkit_mpy_su(mdkit_pi_mt_modal_x(c, index + 1), c->fraction[i]));
    first = mdkit_pi_mt_modal_x(c, c->work[i + 1]);
    c->work[64 + i] = mdkit_acc_to_word(a);
  }
}
/* The eight modes receive a cubic normalization polynomial and measured
 * damping-table taps. Their five MACs preserve the two parallel transfers. */
static inline __attribute__((unused)) void mdkit_pi_mt_modal_coefficients(mdkit_pi_mt_modal *c, uint32_t pitch,
                                         uint32_t decay, uint32_t freq_table,
                                         uint32_t amp_table) {
  uint32_t *y = c->fraction;
  for (unsigned i = 0; i < 8; ++i)
    y[0xb4 + i] = mdkit_acc_to_word(mdkit_mpy(mdkit_pi_mt_modal_y(c, freq_table + i), pitch));
  for (unsigned i = 0; i < 8; ++i) {
    uint32_t f = y[0xb4 + i];
    uint64_t b = mdkit_sub(0, mdkit_mpy(f, f));
    uint64_t a = mdkit_add(mdkit_from24(0x7fffff), b);
    uint32_t old = mdkit_acc_to_word(b);
    b = mdkit_mpy(old, 0x155555);
    a = mdkit_mac(a, mdkit_acc_to_word(b), old);
    y[0xa0 + i] = mdkit_acc_to_word(a);
  }
  for (unsigned i = 0; i < 8; ++i) {
    uint32_t idx =
        mdkit_acc_to_word(mdkit_mpy(mdkit_pi_mt_modal_x(c, amp_table - 8 + i), decay));
    uint32_t damping = mdkit_pi_mt_modal_x(c, 0x142949 + idx);
    uint64_t a =
        mdkit_add(mdkit_asl(mdkit_mpy(damping, y[0xa0 + i]), 1), mdkit_from24(0x800000));
    uint32_t first = mdkit_acc_to_word(a);
    uint64_t b = mdkit_sub(0, mdkit_mpy(damping, damping));
    a = mdkit_add(a, b);
    uint32_t normalized = mdkit_acc_to_word(a);
    uint64_t gain = mdkit_asl(mdkit_mpy(mdkit_pi_mt_modal_x(c, amp_table + i), normalized), 1);
    y[0x64 + 4 * i] = mdkit_acc_to_word(b);
    y[0x65 + 4 * i] = first;
    y[0x66 + 4 * i] = mdkit_acc_to_word(gain);
  }
}
static inline __attribute__((unused)) void mdkit_pi_mt_modal_filter(mdkit_pi_mt_modal *c) {
  uint32_t *w = c->work, *y = c->fraction;

  for (unsigned mode = 0; mode < 8; ++mode) {
    unsigned coef = 0x64 + mode * 4, read = 0x60, write = 0x40;
    uint64_t a = mdkit_from24(c->history[mode][0]);
    a = (a & ~UINT64_C(0xffffff)) | c->history[mode][1];
    uint32_t x1 = c->history[mode][2], x0 = w[read++];
    uint32_t y0 = y[coef];
    coef = mdkit_pi_mt_modal_wrap(coef, 1, 2);
    uint32_t old = mdkit_acc_to_word(a);
    a = mdkit_mac(a, x1, y0);
    x1 = old;
    y0 = y[coef];
    coef = mdkit_pi_mt_modal_wrap(coef, 1, 2);
    a = mdkit_mac(a, x1, y0);
    y0 = y[coef];
    coef = mdkit_pi_mt_modal_wrap(coef, 1, 2);
    uint64_t b = mdkit_from24(w[write]);
    a = mdkit_mac(a, y0, x0);
    y0 = y[coef];
    coef = mdkit_pi_mt_modal_wrap(coef, 1, 2);
    for (unsigned i = 0; i < 31; ++i) {
      b = mdkit_add(b, a);
      x0 = w[read++];
      old = mdkit_acc_to_word(a);
      a = mdkit_mac(a, x1, y0);
      x1 = old;
      y0 = y[coef];
      coef = mdkit_pi_mt_modal_wrap(coef, 1, 2);
      a = mdkit_mac(a, x1, y0);
      w[write++] = mdkit_acc_to_word(b);
      y0 = y[coef];
      coef = mdkit_pi_mt_modal_wrap(coef, 1, 2);
      b = mdkit_from24(w[write]);
      a = mdkit_mac(a, y0, x0);
      y0 = y[coef];
      coef = mdkit_pi_mt_modal_wrap(coef, 1, 2);
    }
    b = mdkit_add(b, a);
    w[write] = mdkit_acc_to_word(b);

    c->history[mode][0] = mdkit_acc_to_word(a);
    c->history[mode][1] = mdkit_low(a);
    c->history[mode][2] = x1;
  }
}

