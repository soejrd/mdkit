"""Generate descriptor declarations from the registered standalone voices."""
from pathlib import Path
import re
import sys
root = Path(__file__).resolve().parents[1]
family_order = {'trx': 0, 'efm': 1, 'pi': 2}
registrations = sorted((root / 'src').glob('*/*/voice.mk'),
    key=lambda path: (family_order.get(path.parent.parent.name, 3),
                      path.parent.parent.name, path.parent.name))
symbols = []
for registration in registrations:
    key = '_'.join(registration.relative_to(root / 'src').parts[:2])
    match = re.search(r'^' + re.escape(key) + r'_VOICE_SYMBOL\s*:=\s*(\w+)\s*$', registration.read_text(), re.M)
    if not match:
        raise SystemExit(f'Invalid voice registration: {registration}')
    symbols.append(match[1])
if not symbols or len(set(symbols)) != len(symbols):
    raise SystemExit('Empty catalog or duplicate descriptor')
output = Path(sys.argv[1])
output.parent.mkdir(parents=True, exist_ok=True)
content = '/* Generated by tools/generate_catalog.py; SPDX-License-Identifier: CC0-1.0 */\n#include "mdkit.h"\n'
content += ''.join(f'extern const mdkit_voice {s};\n' for s in symbols)
content += 'static const mdkit_voice *const mdkit_catalog[] = {\n'
content += ''.join(f'    &{s},\n' for s in symbols)
content += '};\n#define MDKIT_CATALOG_COUNT (sizeof mdkit_catalog / sizeof mdkit_catalog[0])\n'
if not output.exists() or output.read_text() != content:
    output.write_text(content)
